def write_report(result: AuditResult, filepath: str | Path, kind: str = "json") -> None:
    if kind not in ("json", "html"):
        raise ValueError("format must be 'json' or 'html'")
    Path(filepath).write_text(to_html(result) if kind == "html" else to_json(result), encoding="utf-8")
