"""Regenerate static fixtures and sample reports without network requests."""
import json
import sys
from dataclasses import replace
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from cybershield.scanner import ResponseSnapshot, build_result, demo_result
from cybershield.reports import to_html, to_json


def fixtures():
    baseline = demo_result()
    url = baseline.target_url
    hardened = build_result(url, ResponseSnapshot(url, 200, (
        ("Strict-Transport-Security", "max-age=31536000"),
        ("Content-Security-Policy", "default-src 'self'; frame-ancestors 'none'"),
        ("X-Content-Type-Options", "nosniff"),
        ("Referrer-Policy", "strict-origin-when-cross-origin"),
        ("Permissions-Policy", "camera=(), microphone=()"),
        ("Set-Cookie", "demo_session=REDACTED; Secure; HttpOnly; SameSite=Lax"),
    )), ResponseSnapshot(url, 200, ()), demo=True)
    return {key: replace(value, scanned_at="2026-10-19T00:00:00+00:00")
            for key, value in {"baseline": baseline, "hardened": hardened}.items()}


if __name__ == "__main__":
    data = fixtures()
    (ROOT / "docs/demo-data.js").write_text(
        "// Generated by tools/build_demo.py. Simulated offline fixtures; fixed fixture date.\n"
        "window.CYBERSHIELD_DEMO = " + json.dumps({k: v.to_dict() for k, v in data.items()}, indent=2) + ";\n",
        encoding="utf-8")
    for suffix, content in {"json": to_json(data["baseline"]), "html": to_html(data["baseline"])}.items():
        (ROOT / f"examples/demo-audit.{suffix}").write_text(content, encoding="utf-8")
    print("Updated static demo fixtures and example reports.")
